"""Headless previews: render the mascot and the panel without a display.

Two reasons this exists:

1. **It is how the design is verified.**  The overlay's look is generated by
   :mod:`naveed.overlay.mascot` and the panel's proportions come from
   :mod:`naveed.overlay.theme`; rendering both through
   :class:`naveed.render.pillow_canvas.PillowCanvas` means the exact geometry can
   be checked on any machine — including one with no screen, no Qt, and no
   window manager (which is also how the visual regression test runs).
2. **It is what the user looks at** when they want to see the character, export
   it as a transparent PNG, or sanity-check a change to the palette.

``python -m naveed --portrait out.png`` writes an ``out-*`` family of files:
the expression sheet, the transparent mascot, and a full desktop mock with the
panel floating above the mascot over a code-editor backdrop.
"""

from __future__ import annotations

import os
import random
from typing import Dict, Optional, Sequence

from .. import lazy
from ..config import Config, load_config
from .pillow_canvas import PillowCanvas

__all__ = ["render_all", "render_mascot_sheet", "render_mascot_png", "render_panel_mock", "render_desktop_mock"]


def _mascot_module():
    from ..overlay import mascot

    return mascot


def _theme_module():
    from ..overlay import theme

    return theme


def render_mascot_sheet(path: str, *, size: int = 240, states: Optional[Sequence[str]] = None, columns: int = 4) -> str:
    """One image showing every expression, on a neutral dark backdrop."""
    mascot = _mascot_module()
    states = list(states or mascot.STATES)
    padding = int(size * 0.24)
    cell = size + padding * 2
    rows = max(1, (len(states) + columns - 1) // columns)
    canvas = PillowCanvas(cell * columns, cell * rows, background="#14161D")
    for index, state in enumerate(states):
        column, row = index % columns, index // columns
        canvas.gradient(
            column * cell,
            row * cell,
            cell,
            cell,
            [(0.0, "#181B24"), (1.0, "#12141A")],
        )
        mascot.paint_mascot(
            canvas,
            column * cell + padding,
            row * cell + padding,
            size,
            state=state,
            blink=1.0,
            mouth=0.75 if state == "speaking" else (0.35 if state in ("listening", "success") else 0.0),
            phase=0.35,
            squash=0.0,
        )
        canvas.text(
            column * cell + cell / 2.0,
            row * cell + cell - 22,
            state,
            size=15,
            color="#8E96A8",
            weight="bold",
            anchor="mm",
        )
    return canvas.save(path)


def render_mascot_png(path: str, *, size: int = 512, state: str = "idle", mouth: float = 0.0) -> str:
    """The mascot alone on a transparent background (an app-icon style export)."""
    mascot = _mascot_module()
    canvas = PillowCanvas(size, size)
    mascot.paint_mascot(canvas, 0, 0, size, state=state, blink=1.0, mouth=mouth, phase=0.0)
    return canvas.save(path)


def _button(canvas: PillowCanvas, x: float, y: float, w: float, h: float, label: str, accent: str, *, radius: int = 10) -> None:
    """One shortcut button: dark glass with a coloured left edge and a dot."""
    canvas.rect(x, y, w, h, radius=radius, fill="#FFFFFF10")
    canvas.rect(x, y, w, h, radius=radius, outline="#FFFFFF16", outline_width=1)
    canvas.rect(x + 1, y + 6, 3, h - 12, radius=2, fill=accent)
    canvas.circle(x + 15, y + h / 2.0, 3.4, fill=accent)
    canvas.text(x + 26, y + h / 2.0 - 1, label, size=12.5, color="#E8ECF5", anchor="lm")


def _fit_text(canvas: PillowCanvas, text: str, max_width: float, *, size: float) -> str:
    """Truncate *text* with an ellipsis so it never spills out of its button."""
    if canvas.measure(text, size=size)[0] <= max_width:
        return text
    trimmed = text
    while trimmed and canvas.measure(trimmed + "…", size=size)[0] > max_width:
        trimmed = trimmed[:-1]
    return (trimmed + "…") if trimmed else ""


def render_panel_mock(
    path: str,
    *,
    scale: float = 1.6,
    status: str = "Connected",
    model: str = "gpt-4o-mini",
    watching: str = "Watching: code — main.py, quiet",
    activity: str = "You:  open youtube and search lo-fi",
) -> str:
    """The control panel on its own, at a larger scale for documentation.

    Every measurement comes from :class:`naveed.overlay.theme.PanelMetrics`, so
    this mock and the real Qt panel cannot drift apart: if a number changes in the
    theme, both move together.
    """
    theme = _theme_module()
    metrics = theme.PANEL
    palette = theme.PALETTE

    margin = 16
    width = int(metrics.width * scale) + margin * 2
    height = int(metrics.height * scale) + margin * 2
    canvas = PillowCanvas(width, height, background="#0C0E13")

    def u(value: float) -> float:
        """Panel units -> preview pixels."""
        return value * scale

    x0 = margin
    y0 = margin
    body_w = u(metrics.width)
    body_h = u(metrics.height)

    # Shadow, then the glass body and its top highlight.
    for index, alpha in enumerate((20, 28, 36)):
        canvas.rect(
            x0 + index * 0.6,
            y0 + index * 0.9,
            body_w - index * 1.2,
            body_h - index * 1.2,
            radius=u(metrics.radius),
            fill=f"#000000{alpha:02x}",
        )
    canvas.gradient(
        x0, y0, body_w, body_h,
        [(0.0, "#1B1F2B"), (0.55, "#141822"), (1.0, "#101319")],
        radius=u(metrics.radius),
    )
    canvas.rect(x0, y0, body_w, body_h, radius=u(metrics.radius), outline=palette["glass_border"], outline_width=1)
    canvas.gradient(
        x0 + u(10), y0 + 1, body_w - u(20), u(34),
        [(0.0, "#FFFFFF14"), (1.0, "#FFFFFF00")],
        radius=u(10),
    )

    padding = u(metrics.padding)

    # --- header row -------------------------------------------------------
    header_y = y0 + u(11)
    canvas.text(x0 + padding, header_y, "Naveed", size=13.5 * scale / 1.6, color=palette["panel_text"], weight="bold")
    title_w = canvas.measure("Naveed", size=13.5 * scale / 1.6, weight="bold")[0]
    dot_x = x0 + padding + title_w + u(12)
    canvas.circle(dot_x, header_y + u(7), u(4), fill=palette["connected"])
    canvas.text(dot_x + u(10), header_y + u(7), status, size=11 * scale / 1.6, color=palette["panel_muted"], anchor="lm")

    # Header icons are painted from the same vector definitions the Qt panel
    # uses, so the mock and the app cannot disagree — and no glyph falls back to
    # an emoji font (which renders as empty boxes on minimal systems).
    from ..overlay.icons import draw_icon

    icon_size = u(24)
    for index, icon_name in enumerate(("close", "speaker", "settings", "add", "home")):
        icon_x = x0 + body_w - padding - (index + 1) * (icon_size + u(4)) + u(4)
        canvas.rect(icon_x, header_y - u(2), icon_size, icon_size, radius=u(8), fill="#FFFFFF10")
        draw_icon(canvas, icon_name, icon_x + u(5), header_y + u(3), icon_size - u(10), palette["panel_muted"])

    # --- status card (left) -----------------------------------------------
    card_x = x0 + padding
    card_y = header_y + u(20)
    card_w = u(metrics.status_card_width)
    # The card is sized from its own content, exactly like the Qt layout does,
    # so the mock cannot show a card that clips its rows.
    card_h = u(6 + 42 + 16 + 6 + 28 + 8 + 14 + 8)
    canvas.rect(card_x, card_y, card_w, card_h, radius=u(14), fill="#FFFFFF0B")
    canvas.rect(card_x, card_y, card_w, card_h, radius=u(14), outline=palette["glass_border"], outline_width=1)

    mascot = _mascot_module()
    mini_size = u(38)
    mascot.paint_mascot(
        canvas, card_x + u(6), card_y + u(6), mini_size,
        state="idle", blink=1.0, shadow=False, glow=False,
    )
    text_x = card_x + u(6) + mini_size + u(8)
    canvas.text(text_x, card_y + u(10), status, size=12.5 * scale / 1.6, color=palette["connected"], weight="bold")
    canvas.text(text_x, card_y + u(26), model, size=10 * scale / 1.6, color=palette["panel_faint"])

    watching_text = _fit_text(canvas, watching, card_w - u(24), size=10.5 * scale / 1.6)
    canvas.text(card_x + u(12), card_y + u(52), watching_text, size=10.5 * scale / 1.6, color=palette["panel_muted"])

    button_w = (card_w - u(24) - u(6)) / 2.0
    button_h = u(28)
    button_y = card_y + u(70)
    canvas.rect(card_x + u(12), button_y, button_w, button_h, radius=u(9), fill=palette["orange"])
    draw_icon(canvas, "mic", card_x + u(12) + button_w * 0.5 - u(26), button_y + u(7), u(14), "#1A1207")
    canvas.text(card_x + u(12) + button_w * 0.5 + u(4), button_y + button_h / 2.0, "Listen",
                size=11.5 * scale / 1.6, color="#1A1207", weight="bold", anchor="mm")
    canvas.rect(card_x + u(18) + button_w, button_y, button_w, button_h, radius=u(9), fill="#FF5A5F2E")
    canvas.rect(card_x + u(18) + button_w, button_y, button_w, button_h, radius=u(9), outline="#FF5A5F55", outline_width=1)
    draw_icon(canvas, "stop", card_x + u(18) + button_w * 1.5 - u(22), button_y + u(8), u(12), "#FFC9CB")
    canvas.text(card_x + u(18) + button_w * 1.5 + u(5), button_y + button_h / 2.0, "Stop",
                size=11.5 * scale / 1.6, color="#FFC9CB", anchor="mm")

    activity_text = _fit_text(canvas, activity, card_w - u(24), size=9.5 * scale / 1.6)
    canvas.text(card_x + u(12), button_y + button_h + u(8), activity_text, size=9.5 * scale / 1.6, color=palette["panel_faint"])

    # --- shortcut grid (right) ---------------------------------------------
    grid_x = card_x + card_w + u(10)
    grid_w = x0 + body_w - padding - grid_x
    columns = metrics.grid_columns
    gap = u(7)
    cell_w = (grid_w - gap * (columns - 1)) / columns
    cell_h = u(38)
    for index, (label, accent) in enumerate(theme.SHORTCUTS):
        column, row = index % columns, index // columns
        bx = grid_x + column * (cell_w + gap)
        by = card_y + row * (cell_h + gap)
        canvas.rect(bx, by, cell_w, cell_h, radius=u(10), fill="#FFFFFF10")
        canvas.rect(bx, by, cell_w, cell_h, radius=u(10), outline=palette["glass_border"], outline_width=1)
        canvas.rect(bx + 1.5, by + u(7), u(3), cell_h - u(14), radius=u(2), fill=accent)
        canvas.circle(bx + u(14), by + cell_h / 2.0, u(3.4), fill=accent)
        label_size = 12 * scale / 1.6
        fitted = _fit_text(canvas, label, cell_w - u(26), size=label_size)
        canvas.text(bx + u(21), by + cell_h / 2.0, fitted, size=label_size, color=palette["panel_text"], anchor="lm")

    # --- divider, input row, log line --------------------------------------
    divider_y = card_y + card_h + u(8)
    canvas.rect(x0 + padding, divider_y, body_w - padding * 2, 1, fill=palette["glass_border"])

    input_y = divider_y + u(9)
    input_h = u(34)
    send_w = u(38)
    canvas.rect(x0 + padding, input_y, body_w - padding * 2 - send_w - u(8), input_h, radius=u(10), fill="#00000040")
    canvas.rect(x0 + padding, input_y, body_w - padding * 2 - send_w - u(8), input_h, radius=u(10),
                outline=palette["glass_border"], outline_width=1)
    canvas.text(x0 + padding + u(11), input_y + input_h / 2.0, "Tell Naveed what to do on this screen…",
                size=11.5 * scale / 1.6, color=palette["panel_faint"], anchor="lm")
    send_x = x0 + body_w - padding - send_w
    canvas.gradient(send_x, input_y, send_w, input_h, [(0.0, palette["orange"]), (1.0, palette["coral"])], radius=u(10))
    draw_icon(canvas, "send", send_x + send_w * 0.28, input_y + input_h * 0.26, send_w * 0.44, "#1A1207")

    log_y = input_y + input_h + u(10)
    canvas.circle(x0 + padding + u(5), log_y, u(3.2), fill=palette["success"])
    canvas.text(x0 + padding + u(18), log_y, "Typed the search into the box", size=10.5 * scale / 1.6,
                color=palette["panel_muted"], anchor="lm")
    message_w = canvas.measure("Typed the search into the box", size=10.5 * scale / 1.6)[0]
    canvas.text(x0 + padding + u(18) + message_w + u(8), log_y, "·  0.8s", size=10.5 * scale / 1.6,
                color=palette["panel_faint"], anchor="lm")
    return canvas.save(path)


def render_desktop_mock(path: str, *, width: int = 1280, height: int = 800, config: Optional[Config] = None) -> str:
    """The whole thing as the user sees it: mascot + panel over an editor window."""
    config = config or load_config()
    theme = _theme_module()
    mascot = _mascot_module()
    canvas = PillowCanvas(width, height, background="#0B0D12")

    # --- a plausible code editor behind everything -----------------------
    canvas.rect(0, 0, width, 34, fill="#15171E")            # title bar
    canvas.rect(0, 34, 62, height, fill="#141721")          # activity bar
    canvas.rect(62, 34, 300, height, fill="#101319")        # sidebar
    canvas.rect(62 + 300, 34, width - 362, height, fill="#0E1015")  # editor

    for index, (label, colour) in enumerate((("⎇", "#8E96A8"), ("⌕", "#8E96A8"), ("⑂", "#8E96A8"), ("▷", "#8E96A8"))):
        canvas.text(31, 70 + index * 40, label, size=17, color=colour, anchor="mm")

    canvas.text(80, 52, "EXPLORER", size=10.5, color="#6C7486", weight="bold")
    for index in range(14):
        indent = 8 if index % 3 else 0
        shade = 200 - (index * 11) % 70
        canvas.rect(78 + indent, 74 + index * 22, 8, 8, radius=2, fill=f"#{shade:02x}{shade:02x}{shade:02x}22")
        canvas.rect(92 + indent, 76 + index * 22, 90 - (index * 7) % 60, 6, radius=3, fill="#FFFFFF14")
        canvas.rect(196 + indent, 76 + index * 22, 60 - (index * 5) % 40, 6, radius=3, fill="#FFFFFF0D")

    canvas.text(380, 52, "main.py  ·  naveed", size=11.5, color="#7E879A")
    palette = ["#FF8A2B", "#7DD3FC", "#A78BFA", "#34D399", "#FF5B57", "#FBBF24", "#F472B6", "#8E96A8"]
    random.seed(7)
    for line in range(24):
        y = 80 + line * 22
        canvas.rect(384, y, 30, 7, radius=3, fill="#FFFFFF10")
        x = 428
        for _chunk in range(random.randint(2, 5)):
            word_w = random.randint(26, 120)
            if x + word_w > width - 60:
                break
            canvas.rect(x, y, word_w, 7, radius=3, fill=f"{random.choice(palette)}66")
            x += word_w + 12

    # --- the companion, floating in front --------------------------------
    mascot_size = config.overlay.size + 40
    mascot_x = int(width / 2 - mascot_size / 2)
    mascot_y = int(height / 2 + height * config.overlay.offset_from_middle - mascot_size / 2)

    # Panel anchored above the mascot, exactly as the overlay places it.
    # The panel keeps its real proportions and is placed exactly where the
    # overlay puts it: centred above the mascot, clamped inside the screen.
    panel_scale = 0.92
    panel_width = int(theme.PANEL.width * panel_scale)
    panel_height = int(theme.PANEL.height * panel_scale)
    panel_x = max(16, min(mascot_x + mascot_size - panel_width, width - panel_width - 16))
    panel_y = max(16, mascot_y - panel_height - 14)

    mock_path = render_panel_mock("/tmp/_naveed_panel_mock.png", scale=panel_scale)
    PILImage = lazy.load("PIL.Image", extra="capture")
    with PILImage.open(mock_path) as handle:
        panel_image = handle.convert("RGBA")
    margin = 16
    panel_image = panel_image.crop((margin, margin, panel_image.width - margin, panel_image.height - margin))
    canvas.fit(panel_image, panel_x, panel_y)

    mascot.paint_mascot(
        canvas,
        mascot_x,
        mascot_y,
        mascot_size,
        state="speaking",
        blink=1.0,
        mouth=0.7,
        phase=0.4,
    )

    # The transient caption the mascot shows under itself while it works.
    caption = "Typing the search into the box…"
    caption_size = 12.5
    caption_w = canvas.measure(caption, size=caption_size)[0] + 30
    caption_x = mascot_x + mascot_size / 2.0 - caption_w / 2.0
    caption_y = mascot_y + mascot_size * 1.04
    canvas.rect(caption_x, caption_y, caption_w, 30, radius=15, fill="#101219E6")
    canvas.rect(caption_x, caption_y, caption_w, 30, radius=15, outline=theme.PALETTE["glass_border"], outline_width=1)
    canvas.text(caption_x + caption_w / 2.0, caption_y + 15, caption, size=caption_size,
                color=theme.PALETTE["panel_text"], anchor="mm")
    return canvas.save(path)


def render_all(path: str, *, config: Optional[Config] = None, size: int = 240) -> Dict[str, str]:
    """Render every preview next to *path*, returning the written files."""
    base, extension = os.path.splitext(path)
    extension = extension or ".png"
    outputs = {
        "states": render_mascot_sheet(f"{base}-states{extension}", size=size),
        "mascot": render_mascot_png(f"{base}-mascot{extension}", size=size * 2),
        "panel": render_panel_mock(f"{base}-panel{extension}"),
        "desktop": render_desktop_mock(f"{base}-desktop{extension}", config=config),
    }
    return outputs
